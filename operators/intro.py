number_1=20
number_2=10
print(number_1 + number_2)
print(number_1 * number_2)
print(number_1 / number_2)
print(number_1 - number_2)
print(number_1**number_2) #exponential(10^20)
print(number_1//number_2) #floor function (remove the decimal point of division .That is 20/10=2)
print(number_1%number_2) #remainder